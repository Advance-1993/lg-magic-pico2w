// HID REPORT HANDLING
//--------------------------------------------------------------------+

/**
 * @brief Process and enqueue received BLE HID input report.
 * @param service_index Index of the HID service.
 * @param report_id Report ID of the input report.
 * @param report Pointer to report data.
 * @param report_len Length of report data.
 */
static void hid_handle_input_report(uint8_t service_index, uint8_t report_id, const uint8_t * report, uint16_t report_len)
{
    if (!hid_reconnect_input_allowed()) return;
    // If an input report is received while not yet in READY state (e.g. fast reconnect),
    // update app_state to READY and request USB re-init so LED state becomes READY.
    if (app_state != READY) {
        BLE_LOG("HID report received in state %d. Forcing app_state to READY.\n", app_state);
        app_state = READY;
        g_usb_reinit_request = true;
    }
    
    if (!link_first_report_recorded && report_id==0xFD && report_len==20 && report[0]==0xFD) {
        link_first_report_recorded=true;link_record(LINK_FIRST_REPORT,btstack_run_loop_get_time_ms()-link_started_ms);
    }
    bridge_hid_input(report_id, report, report_len);
    diag_hex("REPORT", service_index, report_id, report, report_len);
    return;
}

