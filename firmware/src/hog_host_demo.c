/**
 * @brief Periodic timer callback executed on Core 1 (BTstack run loop) to drive the status LED.
 * @param ts Pointer to timer source structure.
 */
static void led_timer_handler(btstack_timer_source_t * ts)
{
    power_tick();
    reconnect_probe_poll();
    hid_reconnect_poll();
    char cmd[96];
    while (diag_get_command(cmd)) {
        if (hid_reconnect_command(cmd)) continue;
        if (!strncmp(cmd,"forget",6) || !strncmp(cmd,"pair ",5)) hid_reconnect_clear("bond_command");
        if (!strcmp(cmd,"reconnect probe")) {
            if (app_state==READY && connection_handle!=HCI_CON_HANDLE_INVALID) reconnect_probe_start(connection_handle);
            else BLE_LOG("CACHE_PROBE_REJECT requires a ready remote\n");
            continue;
        }
        if (!strcmp(cmd,"history")) { link_dump_history();continue; }
        if (!strcmp(cmd,"power timeout")) { if (power_initialized) power_timeout_status();else BLE_LOG("TIMEOUT_PENDING initializing\n");continue; }
        if (!strncmp(cmd,"power timeout ",14)) {
            uint32_t seconds;
            if (power_timeout_parse(cmd+14,&seconds)) power_timeout_save(seconds);
            else BLE_LOG("TIMEOUT_REJECT choose30/60/90/180 or240..780 in60sec steps\n");
            continue;
        }
        if (!strcmp(cmd,"calibrate") || !strcmp(cmd,"mouse on")) power_manual_resume();
        if (!strcmp(cmd,"power status")) { power_log_status();continue; }
        if (!strcmp(cmd,"power sleep")) { power_apply_action(power_policy_sleep(&power_state,btstack_run_loop_get_time_ms()),"explicit_sleep");continue; }
        if (!strcmp(cmd,"power idle off")) { power_state.idle_enabled=false;power_manual_resume();continue; }
        if (!strcmp(cmd,"power idle on")) { power_state.idle_enabled=LG_ENABLE_HID!=0;power_manual_resume();continue; }
        if (!strcmp(cmd, "status")) {
            BLE_LOG("STATUS state=%d handle=%04X bonded=%u armed=%u connect_enabled=%u last_reencrypt_error=%02X transient_failures=%u\n", app_state, connection_handle, has_bonded_device, pair_armed, connect_enabled, last_reencryption_error, transient_reencryption_failures);
            power_log_status();
            if (has_bonded_device) BLE_LOG("PEER saved=%s type=%u\n", bd_addr_to_str(bonded_device.addr), bonded_device.addr_type);
            if (connection_handle != HCI_CON_HANDLE_INVALID) BLE_LOG("PEER active=%s type=%u\n", bd_addr_to_str(target_device.addr), target_device.addr_type);
        } else if (!strcmp(cmd, "disconnect")) {
            link_record(LINK_MANUAL_PAUSE,0);
            connect_enabled = false;
            pair_armed = false;
            if (connection_handle != HCI_CON_HANDLE_INVALID) gap_disconnect(connection_handle);
        } else if (!strcmp(cmd, "scan")) {
            link_record(LINK_MANUAL_PAUSE,1);
            connect_enabled=false;
            power_manual_resume();
            pair_armed=false;
            bridge_hid_disconnect();
            if (connection_handle != HCI_CON_HANDLE_INVALID) gap_disconnect(connection_handle);
            else if (app_state==W4_CONNECTED) {
                gap_connect_cancel();
                hog_start_scan();
            } else if (app_state!=W4_WORKING) hog_start_scan();
            BLE_LOG("SCAN_ONLY: automatic connections paused; saved bond retained\n");
        } else if (!strcmp(cmd, "resume")) {
            transient_reencryption_failures = 0;
            pending_reconnect_delay_ms = RECONNECT_DELAY_MS;
            connect_enabled = true;
            power_manual_resume();
            BLE_LOG("RECONNECT resumed\n");
        } else if (!strcmp(cmd, "forget")) {
            connect_enabled = false;
            pair_armed = false;
            btstack_tlv_get_instance(&btstack_tlv_singleton_impl, &btstack_tlv_singleton_context);
            if (btstack_tlv_singleton_impl) btstack_tlv_singleton_impl->delete_tag(btstack_tlv_singleton_context, TLV_TAG_HOGD);
            if (has_bonded_device) gap_delete_bonding(bonded_device.addr_type, bonded_device.addr);
            // A failed startup may leave a security key without a HOG identity tag.
            // Also remove keys for the explicitly selected address, if any.
            bool selected_nonzero = false;
            for (unsigned i=0; i<6; ++i) selected_nonzero |= selected_device.addr[i] != 0;
            if (selected_nonzero) gap_delete_bonding(selected_device.addr_type, selected_device.addr);
            has_bonded_device = false;
            if (connection_handle != HCI_CON_HANDLE_INVALID) gap_disconnect(connection_handle);
            BLE_LOG("FORGOT local bond only; awaiting explicit pair selection\n");
        } else if (bridge_hid_command(cmd)) {
            // Mouse and calibration commands run on the Bluetooth core so TLV writes are safe.
        } else {
            unsigned a[6], type;
            char extra;
            int f = sscanf(cmd, "forget %2x:%2x:%2x:%2x:%2x:%2x %u %c", &a[0], &a[1], &a[2], &a[3], &a[4], &a[5], &type, &extra);
            if (f==7 && type<=1) {
                bd_addr_t address;
                for (unsigned i=0;i<6;++i) address[i]=(uint8_t)a[i];
                connect_enabled=false; pair_armed=false;
                gap_delete_bonding((bd_addr_type_t)type,address);
                if (has_bonded_device && bonded_device.addr_type==type && !memcmp(bonded_device.addr,address,6)) {
                    btstack_tlv_get_instance(&btstack_tlv_singleton_impl,&btstack_tlv_singleton_context);
                    if (btstack_tlv_singleton_impl) btstack_tlv_singleton_impl->delete_tag(btstack_tlv_singleton_context,TLV_TAG_HOGD);
                    has_bonded_device=false;
                }
                if (connection_handle!=HCI_CON_HANDLE_INVALID) gap_disconnect(connection_handle);
                BLE_LOG("FORGOT explicit local address %s type=%u; remote unchanged\n",bd_addr_to_str(address),type);
                continue;
            }
            int n = sscanf(cmd, "pair %2x:%2x:%2x:%2x:%2x:%2x %u %c", &a[0], &a[1], &a[2], &a[3], &a[4], &a[5], &type, &extra);
            if (n == 7 && type <= 1 && app_state == W4_HID_DEVICE_FOUND) {
                for (unsigned i=0; i<6; ++i) selected_device.addr[i]=(uint8_t)a[i];
                selected_device.addr_type=(bd_addr_type_t)type;
                power_manual_resume();
                link_record(LINK_PAIR_ARMED,0);
                pair_armed=true;
                connect_enabled=true;
                BLE_LOG("PAIR armed only for %s type=%u\n", bd_addr_to_str(selected_device.addr), type);
            } else BLE_LOG("COMMAND rejected: %s\n", cmd);
        }
    }
    // Indicate the controller-confirmed BLE link, independently of USB/PC state.
    // Keep the light on until DISCONNECTION_COMPLETE invalidates the handle.
    cyw43_arch_gpio_put(CYW43_WL_GPIO_LED_PIN,
        connection_handle != HCI_CON_HANDLE_INVALID);

    // Re-arm the timer
    btstack_run_loop_set_timer(ts, LED_BLINKING_INTERVAL_MS);
    btstack_run_loop_add_timer(ts);
}

