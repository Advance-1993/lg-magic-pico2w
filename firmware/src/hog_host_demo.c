static void link_log_event(const char *prefix,const link_event_t *event) {
    BLE_LOG("%s boot=%08lX seq=%lu uptime_ms=%lu event=%s detail=%lu\n",prefix,
        (unsigned long)link_history.boot,(unsigned long)event->seq,(unsigned long)event->ms,
        link_event_name(event->type),(unsigned long)event->detail);
}
static void link_record(link_event_type_t type,uint32_t detail) {
    link_event_t event=link_history_add(&link_history,btstack_run_loop_get_time_ms(),type,detail);
    link_log_event("LINK_EVENT",&event);
}
static void link_dump_history(void) {
    BLE_LOG("HISTORY_BEGIN boot=%08lX count=%u\n",(unsigned long)link_history.boot,link_history.count);
    for (unsigned i=0;i<link_history.count;++i) link_log_event("HISTORY",link_history_get(&link_history,i));
    BLE_LOG("HISTORY_END boot=%08lX count=%u\n",(unsigned long)link_history.boot,link_history.count);
}
static void link_mark_secured(void) {
    if (link_security_recorded) return;
    link_security_recorded=true;link_secured_ms=btstack_run_loop_get_time_ms();
    link_record(LINK_SECURED,link_secured_ms-link_connected_ms);
}
static void power_timeout_status(void) {
    BLE_LOG("TIMEOUT seconds=%lu source=%s supported=%u\n",(unsigned long)(power_state.idle_timeout_ms/1000u),
        power_timeout_from_flash ? "flash" : "default",LG_ENABLE_HID);
}
static void power_timeout_load(void) {
    const btstack_tlv_t *impl;void *context;power_config_t saved;
    btstack_tlv_get_instance(&impl,&context);
    power_timeout_from_flash=impl && impl->get_tag(context,POWER_CONFIG_TAG,(uint8_t *)&saved,sizeof(saved))==sizeof(saved) && power_config_valid(&saved);
    if (power_timeout_from_flash) power_state.idle_timeout_ms=saved.seconds*1000u;
    power_timeout_status();
}
static void power_timeout_save(uint32_t seconds) {
    if (!power_initialized || !LG_ENABLE_HID || !power_timeout_valid(seconds)) { BLE_LOG("TIMEOUT_REJECT unsupported value/image\n");return; }
    const btstack_tlv_t *impl;void *context;power_config_t candidate=power_config_make(seconds),check;
    btstack_tlv_get_instance(&impl,&context);int rc=-1;bool verified=false;
    if (impl) {
        bool same=impl->get_tag(context,POWER_CONFIG_TAG,(uint8_t *)&check,sizeof(check))==sizeof(check) && !memcmp(&check,&candidate,sizeof(check));
        rc=same ? 0 : impl->store_tag(context,POWER_CONFIG_TAG,(const uint8_t *)&candidate,sizeof(candidate));
        verified=rc==0 && impl->get_tag(context,POWER_CONFIG_TAG,(uint8_t *)&check,sizeof(check))==sizeof(check) && !memcmp(&check,&candidate,sizeof(check));
    }
    if (verified) {
        power_timeout_from_flash=true;
        power_policy_set_timeout(&power_state,btstack_run_loop_get_time_ms(),seconds*1000u);
        bridge_hid_note_activity();link_record(LINK_TIMEOUT_SAVED,seconds);
    }
    BLE_LOG("TIMEOUT_STORE rc=%d readback=%u applied=%u seconds=%lu\n",rc,verified,verified,(unsigned long)seconds);
    power_timeout_status();
}
static bool power_connections_allowed(void) {
    return power_initialized && power_state.host_online && power_state.mode==POWER_ACTIVE && connect_enabled;
}
static void power_log_status(void) {
    host_usb_state_t usb=host_usb_state();uint32_t now=btstack_run_loop_get_time_ms();
    const char *name=power_state.mode==POWER_HOST_OFF ? "usb_off" : power_state.mode==POWER_IDLE ? "idle" : "awake";
    BLE_LOG("POWER state=%s usb_flags=%lu idle_ms=%lu limit_ms=%lu armed=%u enabled=%u peer_quiet_ms=%lu peer_ads=%lu host_pauses=%lu host_resumes=%lu idle_pauses=%lu peer_wakes=%lu manual_wakes=%lu usb_mounts=%lu usb_suspends=%lu usb_resumes=%lu\n",
        name,(unsigned long)usb.flags,(unsigned long)(now-power_state.last_activity_ms),(unsigned long)power_state.idle_timeout_ms,power_state.idle_armed,power_state.idle_enabled,
        (unsigned long)(now-power_state.last_peer_adv_ms),(unsigned long)power_state.idle_peer_ads,
        (unsigned long)power_state.host_pauses,(unsigned long)power_state.host_resumes,(unsigned long)power_state.idle_pauses,
        (unsigned long)power_state.peer_wakes,(unsigned long)power_state.manual_wakes,(unsigned long)usb.mounts,(unsigned long)usb.suspends,(unsigned long)usb.resumes);
}
static void power_apply_action(power_action_t action,const char *reason) {
    if (action==POWER_NOTHING) return;
    if (action==POWER_PAUSE) link_record(power_state.mode==POWER_HOST_OFF ? LINK_USB_OFF : LINK_IDLE,power_state.mode==POWER_HOST_OFF ? 0 : power_state.idle_timeout_ms/1000u);
    else link_record(!strcmp(reason,"usb_available") ? LINK_USB_ON : LINK_RESUME,0);
    BLE_LOG("POWER_EVENT reason=%s action=%s\n",reason,action==POWER_PAUSE ? "pause" : "wake");power_log_status();
    if (action==POWER_PAUSE) {
        pair_armed=false;bridge_hid_disconnect();gap_stop_scan();btstack_run_loop_remove_timer(&connection_timer);clear_all_pending_rpa_lookups();
        if (connection_handle!=HCI_CON_HANDLE_INVALID) gap_disconnect(connection_handle);
        else {
            if (app_state==W4_CONNECTED) gap_connect_cancel();
            hog_start_scan();
        }
    } else {
        bridge_hid_note_activity();
        if (connection_handle==HCI_CON_HANDLE_INVALID && app_state!=W4_CONNECTED) {
            gap_stop_scan();btstack_run_loop_remove_timer(&connection_timer);hog_start_scan();
        }
    }
}
static void power_tick(void) {
    if (!power_initialized) return;
    bool idle_allowed=LG_ENABLE_HID && has_bonded_device && connect_enabled && !pair_armed;
    power_action_t action=power_policy_tick(&power_state,btstack_run_loop_get_time_ms(),host_usb_active(),bridge_hid_last_activity_ms(),idle_allowed);
    power_apply_action(action,power_state.mode==POWER_HOST_OFF ? "usb_unavailable" : action==POWER_PAUSE ? "idle_timeout" : "usb_available");
}
static void power_peer_seen(void) {
    if (power_policy_peer_advertisement(&power_state,btstack_run_loop_get_time_ms())) {
        bridge_hid_note_activity();link_record(LINK_WAKE,0);BLE_LOG("POWER_EVENT reason=fresh_peer_advertisement action=wake\n");power_log_status();
    }
}
static void power_manual_resume(void) {
    power_apply_action(power_policy_resume(&power_state,btstack_run_loop_get_time_ms()),"manual_resume");
    bridge_hid_note_activity();
}

int btstack_main(int argc, const char * argv[])
{
    (void)argc;
    (void)argv;

    link_history_init(&link_history,get_rand_32());link_record(LINK_BOOT,0);
    l2cap_init();

    // setup SM: No Input No Output
    sm_init();
    sm_set_io_capabilities(IO_CAPABILITY_NO_INPUT_NO_OUTPUT);
    sm_set_authentication_requirements(SM_AUTHREQ_SECURE_CONNECTION | SM_AUTHREQ_BONDING);

    gatt_client_init();

    // setup ATT server - only needed if LE Peripheral does ATT queries on its own, e.g. Android and iOS
    att_server_init(profile_data, NULL, NULL);

    hids_client_init(hid_descriptor_storage, sizeof(hid_descriptor_storage));

    // register for events from HCI
    hci_event_callback_registration.callback = &packet_handler;
    hci_add_event_handler(&hci_event_callback_registration);

    // register for events from Security Manager
    sm_event_callback_registration.callback = &sm_packet_handler;
    sm_add_event_handler(&sm_event_callback_registration);

    app_state = W4_WORKING;

    // Start LED blinking timer on BTstack run loop (Core 1)
    btstack_run_loop_set_timer_handler(&led_timer, &led_timer_handler);
    btstack_run_loop_set_timer(&led_timer, LED_BLINKING_INTERVAL_MS);
    btstack_run_loop_add_timer(&led_timer);

    // Turn on the device
    hci_power_control(HCI_POWER_ON);
    return 0;
}

